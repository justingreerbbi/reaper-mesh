import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import nodeSchema from '../packages/protocol/schema.json' with { type: 'json' };
import sensorSchema from '../packages/protocol/sensor-schema.json' with { type: 'json' };

// Generate declarations from the same ordered field descriptors used by the codec.
// Kinds are shared by both schemas; append new kinds only, so existing enum values stay put.
const kinds = [
  'u32',
  'id',
  'commandId',
  'region',
  'label',
  'outcome',
  'hex',
  'messageState',
  'radioMode',
  'channels',
  'version',
  'channelIds',
  'i32',
  'bytes',
];
type Schema = Record<string, { tag: number; fields: Record<string, string> }>;

function validate(schema: Schema) {
  const tags = new Set<number>();
  for (const [name, message] of Object.entries(schema)) {
    if (
      !/^[a-zA-Z][a-zA-Z0-9_]*$/.test(name) ||
      tags.has(message.tag) ||
      message.tag < 1 ||
      message.tag > 255
    ) {
      throw new Error('invalid or duplicate message tag/name');
    }
    tags.add(message.tag);
    if (Object.keys(message.fields).length > 255) throw new Error('too many fields');
    for (const [field, kind] of Object.entries(message.fields)) {
      if (!/^[a-zA-Z][a-zA-Z0-9_]*$/.test(field) || !kinds.includes(kind.replace(/\?$/, ''))) {
        throw new Error('invalid field descriptor');
      }
    }
  }
}

function typescript(schema: Schema, typeName: string, source: string) {
  const variants = Object.entries(schema).map(([type, message]) => {
    const fields = Object.entries(message.fields).map(([name, descriptor]) => {
      const kind = descriptor.replace(/\?$/, '');
      return `${name}${descriptor.endsWith('?') ? '?' : ''}: ${
        kind === 'u32' || kind === 'i32'
          ? 'number'
          : kind === 'region'
            ? "'UNSET' | 'US' | 'EU'"
            : kind === 'radioMode'
              ? "'off' | 'receive' | 'mesh'"
              : kind === 'messageState'
                ? "'receiving' | 'queued' | 'transmitted' | 'acknowledged' | 'failed' | 'rejected' | 'unknown'"
                : kind === 'outcome'
                  ? "'committed' | 'conflict' | 'rejected' | 'unknown'"
                  : 'string'
      }`;
    });
    return `  | Readonly<{ type: '${type}'; ${fields.join('; ')} }>`;
  });
  return (
    `// Generated by tools/generate-protocol.ts; edit ${source} instead.\n` +
    `export type ${typeName} =\n` +
    variants.join('\n') +
    ';\n'
  );
}

const upper = (value: string) => value[0].toUpperCase() + value.slice(1);

// The node header owns the shared Kind and FieldDescriptor types; other schemas include it.
function cpp(schema: Schema, namespace: string, source: string, shared: boolean) {
  const prefix = shared ? '' : 'protocol::';
  return `// Generated by tools/generate-protocol.ts; edit ${source} instead.
#pragma once
#include <cstddef>
#include <cstdint>
${shared ? '' : '#include "reaper/schema.generated.hpp"\n'}namespace reaper::${namespace} {
${shared ? `enum class Kind : std::uint8_t { ${kinds.map(upper).join(', ')} };\n` : ''}enum class MessageType : std::uint8_t { ${Object.entries(
    schema,
  )
    .map(([name, value]) => `${upper(name)} = ${value.tag}`)
    .join(', ')} };
${shared ? 'struct FieldDescriptor { Kind kind; bool optional; };\n' : ''}struct MessageDescriptor { MessageType type; const ${prefix}FieldDescriptor* fields; std::size_t count; };
inline constexpr std::size_t kMaxFields = ${Math.max(...Object.values(schema).map(message => Object.keys(message.fields).length))};
${Object.entries(schema)
  .map(([name, message]) => {
    const fields = Object.entries(message.fields);
    return (
      `inline constexpr ${prefix}FieldDescriptor k${upper(name)}Fields[] = { ${fields
        .map(
          ([, kind]) => `{${prefix}Kind::${upper(kind.replace(/\?$/, ''))}, ${kind.endsWith('?')}}`,
        )
        .join(', ')} };\n` +
      fields
        .map(
          ([field], index) =>
            `inline constexpr std::size_t k${upper(name)}${upper(field)} = ${index};`,
        )
        .join('\n')
    );
  })
  .join('\n')}
inline constexpr MessageDescriptor kMessages[] = {
${Object.entries(schema)
  .map(
    ([name, message]) =>
      `  {MessageType::${upper(name)}, k${upper(name)}Fields, ${Object.keys(message.fields).length}},`,
  )
  .join('\n')}
};
} // namespace reaper::${namespace}
`;
}

validate(nodeSchema as Schema);
validate(sensorSchema as Schema);
const include = '../firmware/components/reaper_protocol/include/reaper/';
const outputs = [
  [
    new URL('../packages/protocol/messages.generated.ts', import.meta.url),
    typescript(nodeSchema as Schema, 'Message', 'schema.json'),
  ],
  [
    new URL(`${include}schema.generated.hpp`, import.meta.url),
    cpp(nodeSchema as Schema, 'protocol', 'schema.json', true),
  ],
  [
    new URL('../packages/protocol/sensor-messages.generated.ts', import.meta.url),
    typescript(sensorSchema as Schema, 'SensorMessage', 'sensor-schema.json'),
  ],
  [
    new URL(`${include}sensor_schema.generated.hpp`, import.meta.url),
    cpp(sensorSchema as Schema, 'sensor', 'sensor-schema.json', false),
  ],
] as const;
if (!process.argv.includes('--check'))
  mkdirSync(new URL(include, import.meta.url), { recursive: true });
for (const [path, expected] of outputs) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== expected)
      throw new Error(`generated protocol output is stale: ${path.pathname}`);
  } else writeFileSync(path, expected);
}
