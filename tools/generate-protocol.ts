import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import schema from '../packages/protocol/schema.json' with { type: 'json' };

// Generate declarations from the same ordered field descriptors used by the codec.
const target = new URL('../packages/protocol/messages.generated.ts', import.meta.url);
const kinds = ['u32', 'id', 'commandId', 'region', 'label', 'outcome', 'hex', 'messageState'];
const tags = new Set<number>();
for (const [name, message] of Object.entries(schema)) {
  if (!/^[a-zA-Z][a-zA-Z0-9_]*$/.test(name) || tags.has(message.tag) || message.tag < 1 || message.tag > 255) {
    throw new Error('invalid or duplicate message tag/name');
  }
  tags.add(message.tag);
  if (Object.keys(message.fields).length > 255) throw new Error('too many fields');
  for (const [field, kind] of Object.entries(message.fields)) {
    if (!/^[a-zA-Z][a-zA-Z0-9_]*$/.test(field) || !kinds.includes(kind.replace(/\?$/, ''))) {
      throw new Error('invalid field descriptor');
    }
  }
}
const variants = Object.entries(schema).map(([type, message]) => {
  const fields = Object.entries(message.fields).map(([name, descriptor]) => {
    const kind = descriptor.replace(/\?$/, '');
    return `${name}${descriptor.endsWith('?') ? '?' : ''}: ${kind === 'u32' ? 'number' :
      kind === 'region' ? "'UNSET' | 'US' | 'EU'" :
      kind === 'messageState' ? "'receiving' | 'queued' | 'transmitted' | 'acknowledged' | 'failed' | 'rejected' | 'unknown'" :
      kind === 'outcome' ? "'committed' | 'conflict' | 'rejected' | 'unknown'" : 'string'}`;
  });
  return `  | Readonly<{ type: '${type}'; ${fields.join('; ')} }>`;
});
const source = '// Generated by tools/generate-protocol.ts; edit schema.json instead.\n' +
  'export type Message =\n' + variants.join('\n') + ';\n';
const upper = (value: string) => value[0].toUpperCase() + value.slice(1);
const cpp = `// Generated by tools/generate-protocol.ts; edit schema.json instead.
#pragma once
#include <cstddef>
#include <cstdint>
namespace reaper::protocol {
enum class Kind : std::uint8_t { ${kinds.map(upper).join(', ')} };
enum class MessageType : std::uint8_t { ${Object.entries(schema).map(([name, value]) => `${upper(name)} = ${value.tag}`).join(', ')} };
struct FieldDescriptor { Kind kind; bool optional; };
struct MessageDescriptor { MessageType type; const FieldDescriptor* fields; std::size_t count; };
inline constexpr std::size_t kMaxFields = ${Math.max(...Object.values(schema).map(message => Object.keys(message.fields).length))};
${Object.entries(schema).map(([name, message]) => {
  const fields = Object.entries(message.fields);
  return `inline constexpr FieldDescriptor k${upper(name)}Fields[] = { ${fields.map(([, kind]) =>
    `{Kind::${upper(kind.replace(/\?$/, ''))}, ${kind.endsWith('?')}}`).join(', ')} };\n` +
    fields.map(([field], index) => `inline constexpr std::size_t k${upper(name)}${upper(field)} = ${index};`).join('\n');
}).join('\n')}
inline constexpr MessageDescriptor kMessages[] = {
${Object.entries(schema).map(([name, message]) => `  {MessageType::${upper(name)}, k${upper(name)}Fields, ${Object.keys(message.fields).length}},`).join('\n')}
};
} // namespace reaper::protocol
`;
const embedded = new URL('../firmware/components/reaper_protocol/include/reaper/schema.generated.hpp', import.meta.url);
if (!process.argv.includes('--check')) mkdirSync(new URL('.', embedded), { recursive: true });
for (const [path, expected] of [[target, source], [embedded, cpp]] as const) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== expected) throw new Error(`generated protocol output is stale: ${path.pathname}`);
  } else writeFileSync(path, expected);
}
