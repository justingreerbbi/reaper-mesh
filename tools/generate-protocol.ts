import { readFileSync, writeFileSync } from 'node:fs';
import schema from '../packages/protocol/schema.json' with { type: 'json' };

// Generate declarations from the same ordered field descriptors used by the codec.
const target = new URL('../packages/protocol/messages.generated.ts', import.meta.url);
const variants = Object.entries(schema).map(([type, message]) => {
  const fields = Object.entries(message.fields).map(([name, kind]) =>
    `${name}: ${kind === 'u32' ? 'number' : kind === 'region' ? "'UNSET' | 'US' | 'EU'" : 'string'}`);
  return `  | Readonly<{ type: '${type}'; ${fields.join('; ')} }>`;
});
const source = '// Generated by tools/generate-protocol.ts; edit schema.json instead.\n' +
  'export type Message =\n' + variants.join('\n') + ';\n';
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== source) throw new Error('generated protocol types are stale');
} else writeFileSync(target, source);
